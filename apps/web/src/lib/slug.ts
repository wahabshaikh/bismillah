/** Turns a name into a URL-safe slug, with a random suffix so it's unique. */
export function slugify(name: string): string {
  const base = name
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return `${base || "org"}-${crypto.randomUUID().slice(0, 6)}`;
}
